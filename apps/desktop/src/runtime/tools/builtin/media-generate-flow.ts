import type { MediaInfo } from '../../../shared/model/media.ts';
import { ABILITY, generationPhase, priceOf } from '../../media/generate.ts';
import { generateRouted, routesFor, type Made, type RouteServices } from '../../media/generate-route.ts';
import type { GenerationKind, GenerationRequest } from '../../media/providers/types.ts';
import { kindOf } from '../../media/probe.ts';
import { MediaRepo } from '../../media/repo.ts';
import { visionImage } from '../../media/vision-image.ts';
import { formatMoney } from '../../spend/ledger.ts';
import type { ActionDescription, JsonSchema, ToolContext, ToolDef, ToolOutput } from '../types.ts';
import { failure, json } from '../types.ts';
import { library, readableMedia } from './media-common.ts';
import { clip, defineTool, internal, isMember, readChat } from './util.ts'; // B-057: readChat

const GENERATED_NOTE = 'Show it in the chat with the ```ui block below (or send the fileId as an attachment).';
const UNLINKED_NOTE = 'This run has no chat of mine, so the file stays private (not linked, not described): attach the fileId to a message to share it.';
const CHARGED_NOTE = 'The provider may already have made and charged it; I check before I try again.';

export interface GenerationToolSpec<A> {
  name: string;
  kind: GenerationKind;
  description: string;
  inputSchema: JsonSchema;
  /** The permission summary, e.g. `Create image "…"`. */
  summary(args: A): string;
  /** The request from the args (and the agent, e.g. its voice). */
  request(args: A, ctx: ToolContext): GenerationRequest;
  /** Live status while it runs, e.g. "creating an image". */
  status: string;
  /** The stored file's name (without extension), description and tags. */
  stored(args: A, made: Made): { name: string; description: string; tags: string[] };
  /** Extra result fields. */
  extra?(args: A, made: Made): Record<string, unknown>;
}

/** Books the price of a paid generation on the agent (model usage, like tokens). */
function recordSpend(ctx: ToolContext, usd: number, ref: string): void {
  try {
    ctx.services.spend.record({ agentId: ctx.agent.id, amount: usd, currency: 'USD', kind: 'tokens', ref: `media:${ref}` });
  } catch (error) {
    ctx.services.log.warn('generation spend not recorded', { error: String(error) });
  }
}

/**
 * A failed paid call that reached the provider may have been charged: effect 'unknown' (no blind
 * retry or failover). Once the provider answered, it made and charged the result: booked as well.
 */
function generationFailure(ctx: ToolContext, error: unknown, usd: number | undefined, answered: boolean, fallback: string): ToolOutput {
  const message = error instanceof WorkforceError ? error.message : fallback;
  const phase = answered ? 'answered' : generationPhase(error);
  if (usd === undefined || !phase) return failure(message);
  if (phase === 'answered') recordSpend(ctx, usd, `run:${ctx.runId}`);
  return { ...failure(`${message} ${CHARGED_NOTE}`), effect: { status: 'unknown' } };
}

/**
 * Stores the generated bytes, links them to the run's chat (when the agent is a member) and
 * describes them (tag 'generated') – only an undescribed row of that chat: an agent-described row
 * without a chat would be visible to every agent (media/repo.ts), and identical bytes that are
 * already in another chat or described keep their row as it is.
 */
async function storeGenerated(ctx: ToolContext, made: Made, input: { name: string; description: string; tags: string[] }): Promise<MediaInfo> {
  const s = ctx.services;
  const file = await s.files.put(made.bytes, input.name, made.mime);
  const home = readChat(ctx); // B-057: a split's media belong to its parent's chat (F-52 hides a people's chat's from the owner)
  const chatId = home && isMember(ctx, home) ? home : undefined;
  const repo = new MediaRepo(s.db);
  const now = s.clock.now();
  // The FileStore hook records the row in the app; insert/link keep this correct without it.
  if (!repo.insert({ fileId: file.id, name: file.name, mime: file.mime, kind: kindOf(file.mime), conversationId: chatId, width: file.width, height: file.height, durationMs: file.durationMs ?? made.durationMs, now }) && chatId) {
    repo.link(file.id, chatId, now);
  }
  const row = repo.get(file.id)!;
  if (!chatId || row.conversationId !== chatId || row.describedBy) return row;
  return library(ctx).describe(file.id, { description: input.description, tags: input.tags }, ctx.agent.id);
}

/** A ready ```ui media block for the chat. */
function mediaSnippet(info: MediaInfo): string {
  const kind = info.kind === 'audio' || info.kind === 'video' ? info.kind : 'image';
  return `\`\`\`ui\n${JSON.stringify({ type: 'media', fileId: info.fileId, kind })}\n\`\`\``;
}

const EXTENSION: Record<string, string> = {
  'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'audio/mpeg': 'mp3', 'audio/wav': 'wav', 'audio/ogg': 'ogg',
  'audio/flac': 'flac', 'audio/mp4': 'm4a', 'video/mp4': 'mp4', 'video/webm': 'webm', 'video/quicktime': 'mov',
};

/** "a-red-fox-in-snow.png" from the prompt (≤ 48 characters). */
function fileName(text: string, made: Made): string {
  const base = text.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48).replace(/-+$/, '');
  return `${base || 'generated'}.${EXTENSION[made.mime] ?? made.extension}`;
}

/**
 * The stored image a video starts from (one the agent may read), as bytes for the adapter – review fix: through the
 * one image normalizer (media/vision-image.ts: PNG/JPEG/WebP within IMAGE_LIMITS.maxPx and ~3.75 MB as they are, else
 * a converted copy), so a phone photo (HEIC, 12 MB JPEG), an SVG or a TIFF is not sent raw and refused by the provider.
 */
async function startImage(ctx: ToolContext, request: GenerationRequest): Promise<GenerationRequest | ToolOutput> {
  if (!request.imageFileId) return request;
  const found = readableMedia(ctx, request.imageFileId, 'animate');
  if ('refused' in found) return found.refused;
  if (found.info.kind !== 'image') return failure('imageFileId must be a stored image.');
  try {
    const shown = await visionImage(ctx.services, { fileId: found.info.fileId, mime: found.info.mime });
    return { ...request, imageFileId: found.info.fileId, image: { bytes: shown.data, mime: shown.mime } };
  } catch (error) {
    return failure(error instanceof WorkforceError ? error.message : 'The start image could not be read.');
  }
}

/** One generation tool from its spec (see the header). */
export function generationTool<A extends object>(spec: GenerationToolSpec<A>): ToolDef {
  const services = (ctx: ToolContext) => ctx.services as RouteServices;
  return defineTool<A>({
    name: spec.name,
    description: spec.description,
    inputSchema: spec.inputSchema,
    category: 'write_local',
    describe(args, ctx): ActionDescription {
      const summary = spec.summary(args);
      let usd: number | undefined;
      let modelId: string | undefined;
      let provider: string | undefined;
      try {
        const first = routesFor(services(ctx), spec.kind).first; // run() explains a missing setup
        if (first?.via === 'model') {
          usd = priceOf(first.target, spec.request(args, ctx));
          modelId = first.target.modelId;
          provider = first.target.account.provider;
        }
      } catch { usd = undefined; }
      if (usd === undefined) return internal(summary, ctx.conversationId);
      return { summary: `${summary} with ${modelId} (about ${formatMoney(usd, 'USD')})`, resource: provider, reversible: false, external: true };
    },
    async run(args, ctx) {
      let usd: number | undefined;
      let answered = false;
      try {
        const routes = routesFor(services(ctx), spec.kind);
        if (!routes.first) return failure((routes.error ?? new WorkforceError('unavailable', `${ABILITY[spec.kind].what} is not set up.`)).message);
        const asked = await startImage(ctx, spec.request(args, ctx));
        if ('content' in asked) return asked;
        usd = routes.first.via === 'model' ? priceOf(routes.first.target, asked) : undefined;
        ctx.status(spec.status);
        const made = await generateRouted(services(ctx), routes, asked, { signal: ctx.signal, agentId: ctx.agent.id, onStatus: (note) => ctx.status(note) });
        if (made.via !== 'model') usd = undefined; // a free fallback made it
        else if (usd !== undefined && made.usd !== undefined && made.usd >= 0) usd = Math.max(0.01, Math.ceil(made.usd * 100 - 1e-9) / 100); // the provider's own price
        answered = true;
        const stored = spec.stored(args, made);
        const info = await storeGenerated(ctx, made, { name: fileName(stored.name, made), description: stored.description, tags: stored.tags });
        if (usd !== undefined) recordSpend(ctx, usd, info.fileId);
        return json({
          ok: true, fileId: info.fileId, mime: info.mime, bytes: info.size, model: made.model,
          ...(made.durationMs ? { durationS: Math.round(made.durationMs / 100) / 10 } : {}),
          ...(spec.extra?.(args, made) ?? {}), ...(made.note ? { fallback: made.note } : {}),
          ui: mediaSnippet(info), note: info.conversationId ? GENERATED_NOTE : UNLINKED_NOTE,
        });
      } catch (error) {
        return generationFailure(ctx, error, usd, answered, `Creating the ${ABILITY[spec.kind].noun} failed.`);
      }
    },
  });
}

/** "Generated image (model): prompt" – the stored description. */
export const describedAs = (what: string, made: Made, text: string, extra = '') => `Generated ${what} (${made.model}${extra}): ${clip(text.trim(), 1500)}`;
