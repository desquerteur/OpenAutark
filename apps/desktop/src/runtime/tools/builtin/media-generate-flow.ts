// The one flow of every generation tool (MM3, B-058 G11–G13: media.image, media.speak, media.music,
// media.sound, media.video): the route (media/generate-route.ts – the function model, else the free fallback
// of the kind), the summary, the run, storage and booking. On a pay-per-use account the call's estimated USD price
// shows in its summary and it is booked on the agent as model usage after it ran (the provider's reported price
// when it names one). The file is
// stored, described (tag 'generated'), linked to the run's chat – without a chat of the agent it stays
// private: not linked, not described – and returned with its fileId and a ```ui media block.
// Owns: the builder, the image a video starts from (read here, never by an adapter, and only one the agent may
// read), storage and booking.
// Never: hides a failure after the request went out – that is an 'unknown' effect (it may have been charged;
// booked once the provider answered); a free fallback is never booked.

