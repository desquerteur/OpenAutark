// B-058 G11–G13: one HTTP exchange of a media generation provider, shared by every adapter
// (providers/*.ts) – a POST or GET with the key header the adapter sets, no redirects unless asked (a
// provider's result download), the answer read within a byte cap, and the call's deadline
// (GenerationContext.deadlineMs) and the run's stop covering the whole exchange, body included.
// Failures are user-safe WorkforceErrors that say how far the call got (details.phase, see
// generationPhase) and whether another route may serve the request instead (details.fallback: the
// account, key, URL or model is not usable – nothing was made or charged). B-058 i1: a POST whose
// connection failed is 'sent' (effect unknown, no fallback or retry) unless the failure provably came
// before the request left (name lookup, refused connect, TLS, bad URL – maybeSent); every exchange
// runs on its own agent whose header/body timeouts outlast every call deadline (Node's fetch ends a
// request after 300 s without headers – shorter than a 6-min video call).
// Owns: the exchange, the HTTP status → error mapping, the phase/fallback markers, the per-kind byte
// caps, the long-timeout agent and the format sniffing of generated bytes. Never: reads keys (the adapter
// passes its header), logs or returns a key or a provider's raw error body, or decides whether a paid call may run.

import { WorkforceError } from '../../shared/errors.ts';
import type { GenerationContext, GenerationKind } from './providers/types.ts';

/** Largest generated file per kind (more is an error, never a truncation). */
export const GENERATED_MAX_BYTES: Record<GenerationKind, number> = {
  image: 20 * 1024 * 1024, speech: 20 * 1024 * 1024, music: 60 * 1024 * 1024, sound: 20 * 1024 * 1024, video: 200 * 1024 * 1024,
};

/**
 * How far a failed call got (WorkforceError.details.phase): 'sent' – the request went out and no
 * answer came (timeout or stop while waiting), so the provider may have made and charged it;
 * 'answered' – the provider accepted it (2xx) and made and charged the result, but the answer broke
 * off, was stopped or was unusable. None: nothing was sent, or the provider refused the request.
 */
export type GenerationPhase = 'sent' | 'answered';

export function generationPhase(error: unknown): GenerationPhase | undefined {
  const phase = error instanceof WorkforceError ? error.details?.phase : undefined;
  return phase === 'sent' || phase === 'answered' ? phase : undefined;
}

export const reached = (phase: GenerationPhase) => ({ details: { phase } });

/** Marks a setup failure (account, key, URL or model unusable; nothing made): another route may serve. */
export const unusable = (message: string) => new WorkforceError('unavailable', message, { details: { fallback: true } });

/** The route failed before anything was made or charged, so a fallback route (plan image, local voice) may serve. */
export function mayFallBack(error: unknown): boolean {
  return error instanceof WorkforceError && !generationPhase(error) && error.details?.fallback === true;
}

/** `error` with `phase` (an adapter's later step of an accepted job: polling, the result download). */
export function atPhase(error: unknown, phase: GenerationPhase, fallback: string): WorkforceError {
  const message = error instanceof WorkforceError ? error.message : fallback;
  const code = error instanceof WorkforceError ? error.code : 'unavailable';
  return new WorkforceError(code, message, reached(generationPhase(error) ?? phase));
}

export interface MediaRequest {
  url: string;
  method?: 'POST' | 'GET';
  headers?: Record<string, string>;
  /** A JSON body (serialised here, content-type set). */
  json?: unknown;
  /** A raw body instead (form data, bytes). */
  body?: BodyInit;
  /** The ability in errors, e.g. "Image generation". */
  what: string;
  /** Answer cap in bytes. */
  max: number;
  /** Follow redirects (a provider's result download); refused by default. */
  follow?: boolean;
}

export interface MediaAnswer { raw: Buffer; type: string; status: number; headers: Headers }

/** The user-safe error of an HTTP failure (never the provider's body). */
export function httpFailure(status: number, what: string): WorkforceError {
  const lower = what.toLowerCase();
  if (status === 401 || status === 403) return unusable(`The provider rejected the ${lower} account. Reconnect it in Settings › Models.`);
  if (status === 404) return unusable(`The ${lower} model or endpoint was not found (HTTP 404). Choose another model.`);
  if (status === 402) return unusable(`The ${lower} account has no credit left (HTTP 402). Top it up or choose another model.`);
  if (status === 429) return new WorkforceError('rate_limited', `The ${lower} limit of the provider was reached. Try again later.`, { details: { fallback: true } });
  if (status === 400 || status === 422) return new WorkforceError('bad_request', `The ${lower} model did not accept the request (HTTP ${status}). Rephrase it or choose another model.`);
  return new WorkforceError('unavailable', `${what} failed (HTTP ${status}).`);
}

/** Header and body timeouts of the media agent: longer than every call deadline (video 6 min + grace); the call's own timer ends it. */
export const MEDIA_SOCKET_MS = 10 * 60_000;
const NODE_DISPATCHER = Symbol.for('undici.globalDispatcher.1');
let mediaAgent: object | null | undefined;

/**
 * The fetch dispatcher for media exchanges: an agent of Node's own fetch (undici is no dependency, so its
 * class is taken from Node's global dispatcher) with MEDIA_SOCKET_MS timeouts. Undefined where Node's fetch
 * has no such dispatcher (the request then keeps the default; a cut POST still ends 'sent').
 */
export function mediaDispatcher(): object | undefined {
  if (mediaAgent === undefined) {
    mediaAgent = null;
    try {
      void globalThis.Response; // loads Node's fetch module, which installs its global dispatcher
      const Agent = ((globalThis as Record<symbol, unknown>)[NODE_DISPATCHER] as { constructor?: unknown } | undefined)?.constructor;
      if (typeof Agent === 'function' && /^(?:Agent|EnvHttpProxyAgent)$/.test(Agent.name)) {
        const agent = new (Agent as new (options: object) => object)({ headersTimeout: MEDIA_SOCKET_MS, bodyTimeout: MEDIA_SOCKET_MS });
        if (typeof (agent as { dispatch?: unknown }).dispatch === 'function') mediaAgent = agent;
      }
    } catch { mediaAgent = null; }
  }
  return mediaAgent ?? undefined;
}

/**
 * Failures that end a request before it leaves this PC: name lookup, a refused or timed-out connect, TLS, a
 * bad URL or request header, a refused redirect (the provider answered 3xx). A reset, a closed socket or a
 * header/body timeout come after sending (undici UND_ERR_SOCKET / ECONNRESET / UND_ERR_HEADERS_TIMEOUT …).
 */
const UNSENT = /\b(?:ENOTFOUND|EAI_AGAIN|EAI_FAIL|EAI_NONAME|ECONNREFUSED|EHOSTUNREACH|ENETUNREACH|ENETDOWN|EADDRNOTAVAIL|UND_ERR_CONNECT_TIMEOUT|UND_ERR_INVALID_ARG|ERR_INVALID_URL|ERR_TLS_[A-Z_]+|ERR_SSL_[A-Z_]+|CERT_[A-Z_]+|[A-Z_]*SELF_SIGNED_CERT[A-Z_]*|UNABLE_TO_[A-Z_]+)\b|unexpected redirect|Failed to parse URL|Invalid URL|is an invalid header (?:name|value)/;

/** Whether the request may have left before this fetch failure: false only when its code or message (along the cause chain) shows it ended before sending. */
export function maybeSent(error: unknown): boolean {
  let current: unknown = error;
  for (let depth = 0; current && typeof current === 'object' && depth < 5; depth += 1) {
    const { code, message, cause } = current as { code?: unknown; message?: unknown; cause?: unknown };
    if (UNSENT.test(`${typeof code === 'string' ? code : ''} ${typeof message === 'string' ? message : ''}`)) return false;
    current = cause;
  }
  return true;
}

/** One exchange within the call's deadline and the run's stop (see the header). */
export async function mediaExchange(ctx: GenerationContext, request: MediaRequest): Promise<MediaAnswer> {
  const { what } = request;
  if (ctx.signal?.aborted) throw new WorkforceError('cancelled', 'Stopped.');
  const ms = Math.max(1, ctx.deadlineMs - Date.now());
  const controller = new AbortController();
  let late = false;
  const abort = () => controller.abort();
  ctx.signal?.addEventListener('abort', abort, { once: true });
  const timer = setTimeout(() => { late = true; abort(); }, ms);
  (timer as { unref?: () => void }).unref?.();
  const ended = (phase: GenerationPhase): WorkforceError | undefined => {
    if (late) return new WorkforceError('timeout', `${what} timed out after ${Math.max(1, Math.round(ms / 1000))} s.`, reached(phase));
    if (controller.signal.aborted) return new WorkforceError('cancelled', 'Stopped.', reached(phase));
    return undefined;
  };
  try {
    let response: Response;
    const method = request.method ?? 'POST';
    try {
      const json = request.json !== undefined;
      const dispatcher = mediaDispatcher();
      response = await ctx.fetch(request.url, {
        method,
        headers: { ...(json ? { 'content-type': 'application/json' } : {}), ...(request.headers ?? {}) },
        body: json ? JSON.stringify(request.json) : request.body,
        redirect: request.follow ? 'follow' : 'error', signal: controller.signal,
        ...(dispatcher ? { dispatcher } : {}),
      } as RequestInit);
    } catch (error) {
      const stopped = ended('sent');
      if (stopped) throw stopped;
      // A POST that may have left can have been made and charged: unknown effect, never a fallback or retry.
      // A GET (status, download) charges nothing and stays a plain network failure (retried by job.ts).
      if (method === 'POST' && maybeSent(error)) throw new WorkforceError('unavailable', `The connection to the ${what.toLowerCase()} service broke off after the request was sent.`, reached('sent'));
      throw unusable(`Could not reach the ${what.toLowerCase()} service.`);
    }
    if (!response.ok) {
      await response.body?.cancel().catch(() => undefined);
      throw httpFailure(response.status, what);
    }
    try {
      const raw = await readCapped(response, request.max, what, controller.signal);
      return { raw, type: response.headers.get('content-type')?.split(';')[0].trim().toLowerCase() ?? '', status: response.status, headers: response.headers };
    } catch (error) {
      throw ended('answered') ?? (error instanceof WorkforceError ? error : new WorkforceError('unavailable', `The ${what.toLowerCase()} answer broke off.`, reached('answered')));
    }
  } finally {
    clearTimeout(timer);
    ctx.signal?.removeEventListener('abort', abort);
  }
}

/** Reads at most `max` bytes of the answer (more is an error, not a truncation); stops when `signal` aborts. */
async function readCapped(response: Response, max: number, what: string, signal: AbortSignal): Promise<Buffer> {
  const tooLarge = () => new WorkforceError('unavailable', `The ${what.toLowerCase()} answer is too large.`, reached('answered'));
  const declared = Number(response.headers.get('content-length') ?? NaN);
  if (Number.isFinite(declared) && declared > max) {
    await response.body?.cancel().catch(() => undefined);
    throw tooLarge();
  }
  const reader = response.body?.getReader();
  if (!reader) throw new WorkforceError('unavailable', `${what} returned no answer.`, reached('answered'));
  // A body that is not fetch's own ignores the request's abort: cancelling the reader ends a pending read.
  const cancel = () => { reader.cancel().catch(() => undefined); };
  signal.addEventListener('abort', cancel, { once: true });
  const chunks: Uint8Array[] = [];
  let size = 0;
  try {
    for (;;) {
      if (signal.aborted) { cancel(); throw new Error('aborted'); }
      const { done, value } = await reader.read();
      if (signal.aborted) throw new Error('aborted'); // a cancelled read ends as "done": never a partial answer
      if (done) break;
      size += value.byteLength;
      if (size > max) { await reader.cancel().catch(() => undefined); throw tooLarge(); }
      chunks.push(value);
    }
  } finally {
    signal.removeEventListener('abort', cancel);
  }
  return Buffer.concat(chunks);
}

const latin = (bytes: Uint8Array, from: number, to: number) => Buffer.from(bytes.subarray(from, to)).toString('latin1');

/** The image format from its first bytes (PNG, JPEG, WebP), or undefined. */
export function imageMime(bytes: Uint8Array): string | undefined {
  if (bytes.length > 8 && bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47) return 'image/png';
  if (bytes.length > 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return 'image/jpeg';
  if (bytes.length > 12 && latin(bytes, 0, 4) === 'RIFF' && latin(bytes, 8, 12) === 'WEBP') return 'image/webp';
  return undefined;
}

/** Audio or video formats from their first bytes (WAV, MP3, Ogg, FLAC, MP4/MOV, WebM), or undefined. */
export function avMime(bytes: Uint8Array): string | undefined {
  if (bytes.length < 12) return undefined;
  if (latin(bytes, 0, 4) === 'RIFF' && latin(bytes, 8, 12) === 'WAVE') return 'audio/wav';
  if (latin(bytes, 0, 3) === 'ID3' || (bytes[0] === 0xff && (bytes[1] & 0xe0) === 0xe0)) return 'audio/mpeg';
  if (latin(bytes, 0, 4) === 'OggS') return 'audio/ogg';
  if (latin(bytes, 0, 4) === 'fLaC') return 'audio/flac';
  if (latin(bytes, 4, 8) === 'ftyp') return /^(qt  )/.test(latin(bytes, 8, 12)) ? 'video/quicktime' : /^M4A /.test(latin(bytes, 8, 12)) ? 'audio/mp4' : 'video/mp4';
  if (bytes[0] === 0x1a && bytes[1] === 0x45 && bytes[2] === 0xdf && bytes[3] === 0xa3) return 'video/webm';
  return undefined;
}
