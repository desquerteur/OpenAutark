// Stored compaction observations: one current knowledge row of kind 'observation' per
// (conversation, agent), scope 'conversation'. Older versions stay as expired history rows.
// Owns: the title convention that records how far a summary reaches ("… up to #240"), the
// marks of a compaction row (tag 'compaction', source ref = the chat) and the lookup of the
// current row (and how far the agent's own one reaches – CTX7's compaction trigger and run
// note). Never: writes (compact.ts does that through KnowledgeService), or treats a note
// an agent saved with knowledge.remember (kind 'observation' is allowed there) as a runtime
// summary – it would be shown to other agents as "generated by the runtime".

import type { RuntimeServices } from '../contracts.ts';
import type { KnowledgeItem } from '../../shared/model/knowledge.ts';

const UPTO = /up to #(\d+)/;
export const COMPACTION_TAG = 'compaction';

export function observationTitle(uptoSeq: number): string {
  return `Chat observations up to #${uptoSeq}`;
}

/** Source of a compaction row (tools cannot set a source; knowledge.remember uses the run id). */
export function observationSource(conversationId: string): KnowledgeItem['source'] {
  return { kind: 'agent', ref: conversationId, trusted: true };
}

/** Highest message seq the observation summarizes (0 when unknown). */
export function coveredSeq(item: Pick<KnowledgeItem, 'title'> | undefined): number {
  const match = item ? UPTO.exec(item.title) : null;
  return match ? Number(match[1]) : 0;
}

function fromCompaction(row: KnowledgeItem, conversationId: string): boolean {
  return row.tags.includes(COMPACTION_TAG) && row.source.kind === 'agent' && row.source.ref === conversationId;
}

/** The agent's current observation for a chat; another agent's newest one as a fallback. */
export function latestObservation(services: RuntimeServices, conversationId: string, agentId: string, options: { ownOnly?: boolean } = {}): KnowledgeItem | undefined {
  let rows: KnowledgeItem[];
  try {
    rows = services.knowledge.observations({ scope: 'conversation', scopeId: conversationId, limit: 20 });
  } catch {
    return undefined;
  }
  const live = rows.filter((row) => !row.expiredAt && fromCompaction(row, conversationId));
  return live.find((row) => row.createdBy === agentId) ?? (options.ownOnly ? undefined : live[0]);
}

/** Highest seq the agent's own current observation of the chat summarizes (0 without one). */
export function ownCoveredSeq(services: RuntimeServices, conversationId: string, agentId: string): number {
  return coveredSeq(latestObservation(services, conversationId, agentId, { ownOnly: true }));
}
